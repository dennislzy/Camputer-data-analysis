import os

from langchain_openai import ChatOpenAI
from langgraph.graph import StateGraph

from node.comment_node import summarize_content
from node.state import AnalysisState
from node.statistics_node import summarize_statistics
from langgraph.graph.state import END


def create_final_result_node(state: AnalysisState):
    """整合最終結果的節點 - 保持原有邏輯"""
    model = ChatOpenAI(
        api_key=os.getenv('OPEN_AI_KEY'),
        model='gpt-4o-mini'
    )

    content_analysis = state["content_analysis"]
    statistics_analysis = state["statistics_analysis"]

    prompt = f"""
   基於以下內容分析和統計數據，請提供綜合洞察並推薦主辦活動的定價策略：

    ## 用戶評論分析結果
    {content_analysis}
    
    ## 關鍵統計數據
    {statistics_analysis}
    
    請根據上述分析，提供以下資訊：
    
    ## 輸出格式
    ### 📊 市場洞察摘要
    - **用戶滿意度**：[從內容分析提取的關鍵滿意度指標]
    - **市場競爭力**：[從統計數據的營隊總數和平均報名率評估]
    - **價格敏感度**：[基於成功/失敗案例的價格差異分析用戶對價格的敏感程度]
    
    ### 💰 推薦活動定價
    **基礎定價建議**：
    - 建議價格範圍：NT$ [僅基於高報名率營隊的價格範圍，絕對不要包含0%報名率的價格]
    - 定價依據：[引用具體的成功案例camp_id和數據作為依據，說明為什麼排除失敗案例價格]
    
    **優化策略**：
    - 早鳥折扣：建議 NT$ [具體金額]元，理由：[基於成功案例的折扣金額，不要使用百分比]
    - 團體折扣：建議 NT$ [具體金額]元，理由：[基於成功案例的折扣金額，不要使用百分比]  
    - 價格彈性調整：[基於失敗案例的風險點提出調整建議]
    
    ### 🎯 定價策略建議
    1. **競爭優勢定位**：[基於成功案例的主辦方類型和定價策略]
    2. **價值主張強化**：[基於內容分析和成功案例的價值提升建議]
    3. **風險控制**：[基於失敗案例的具體風險點和預防措施，明確指出哪些價格區間風險極高]
    
    ### 📈 預期效益
    - **預估報名率**：[基於建議定價範圍和歷史成功案例的報名率預估]
    - **營收優化**：[具體計算相較於當前市場表現的營收改善數字]
    - **競爭優勢**：[基於統計數據分析的競爭優勢]
    
    **重要分析要求**：
    - **絕對禁止**：不要將0%報名率的營隊價格納入推薦範圍
    - **成功案例導向**：價格建議必須基於報名率>50%的營隊數據
    - **具體數字引用**：必須引用統計數據中的具體 camp_id、價格、報名率
    - **邏輯一致性**：如果某價格導致0%報名率，不能同時說它"有風險"又推薦它
    - **折扣策略**：使用具體金額(NT$ XXX元)而非百分比，基於成功案例的實際折扣
    - **風險警告**：明確指出失敗案例的價格上限作為風險紅線
    - **不要計算每日價格**：除非統計數據中包含營隊天數信息
    **數據特殊情況處理**：
    - 報名率 > 1.0 表示超額報名（爆滿），這是極度成功的案例
    - 報名率 = 0 表示完全失敗，絕對不可納入推薦範圍
    - 必須區分：一般成功(0.5-1.0)、爆滿成功(>1.0)、失敗(0)
    - 超額報名案例特別珍貴，需重點分析其成功要素
    
    **價格分析要求**：
    - 基於成功案例建立價格區間，超額報名案例可作為價格上限參考
    - 明確指出價格"死亡線"（如7000元以上風險極高）
    - camp_id 30的8500元成功是特例，需分析其特殊性（主辦方、時間等）
    
    **錯誤示例（禁止出現）**：
    - "建議價格範圍：NT$ 6000 - NT$ 8500"（8500導致0%報名率）
    - "早鳥折扣：10%"（應該用具體金額）
    - "每日平均價格：NT$ 234"（沒有天數數據）
    """

    response = model.invoke(prompt)
    state["final_result"] = response.content
    return state
